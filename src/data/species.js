/**
 * MVP launch roster: direction sets with consistent silhouettes and style.
 * Other authored animals remain available in the showcase for the next art pass.
 */
export const LAUNCH_CUSTOMER_IDS = [
  'bunny',
  'dog',
  'frog',
  'crocodile',
  'owl',
  'panda',
  'penguin',
  'pig',
  'squirrel',
  'red_panda',
];

export const CUSTOMER_SPECIES = LAUNCH_CUSTOMER_IDS
  .map((id) => SPECIES[id])
  .filter(Boolean);

/** Friendly early-day guests with simple favorite recipes */
export const EASY_CUSTOMER_IDS = ['dog', 'bunny', 'panda', 'frog', 'squirrel', 'red_panda'];

export function getSpecies(id) {
  return SPECIES[id] || SPECIES.bunny;
}

export function randomCustomerSpecies(rng = Math.random, easyPool = false) {
  const pool = easyPool
    ? EASY_CUSTOMER_IDS.map((id) => SPECIES[id]).filter(Boolean)
    : CUSTOMER_SPECIES;
  return pool[Math.floor(rng() * pool.length)] || SPECIES.dog;
}
